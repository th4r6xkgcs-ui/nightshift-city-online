'use strict';
// Runs before `wrangler deploy` (see wrangler.jsonc "build").
// Packs into src/static.gen.js:
//  - the server test page and shared browser scripts (always)
//  - when the full game is in the repo: its index.html assets, the generated
//    online.html (served at "/"), and the original solo game at "/solo"
//  - the client's city catalog (city-data.js, when present) as CITY_LAYOUT
const fs = require('node:fs');
const path = require('node:path');
const { STATIC } = require('../server/static-files.js');
const { readGame, onlineHtml } = require('../online/build-online.cjs');

const ROOT = path.join(__dirname, '..');
const serverDir = path.join(ROOT, 'server');
const HTML = 'text/html; charset=utf-8', JS = 'text/javascript; charset=utf-8', CSS = 'text/css; charset=utf-8';
const files = {};
for (const [route, f] of Object.entries(STATIC)) {
  files[route] = { type: f.type, body: fs.readFileSync(path.join(serverDir, f.file), 'utf8') };
}
files['/test'] = files['/']; // the bare server test page stays reachable

const game = readGame();
if (game) {
  for (const s of game.scripts) files['/' + s] = { type: JS, body: fs.readFileSync(path.join(ROOT, s), 'utf8') };
  for (const s of game.styles) files['/' + s] = { type: CSS, body: fs.readFileSync(path.join(ROOT, s), 'utf8') };
  files['/online.js'] = { type: JS, body: fs.readFileSync(path.join(ROOT, 'online', 'online.js'), 'utf8') };
  files['/'] = { type: HTML, body: onlineHtml(game.html) };
  files['/solo'] = { type: HTML, body: game.html };
}

let layout = null;
const catalog = path.join(ROOT, 'city-data.js');
if (fs.existsSync(catalog)) {
  const { layout: make } = require(catalog);
  layout = typeof make === 'function' ? make() : null;
}

const out = path.join(__dirname, 'src', 'static.gen.js');
fs.writeFileSync(out,
  '// GENERATED by worker/build.cjs — do not edit.\n'
  + `export const FILES = ${JSON.stringify(files)};\n`
  + `export const CITY_LAYOUT = ${JSON.stringify(layout)};\n`);
const kb = Math.round(fs.statSync(out).size / 1024);
console.log(`static.gen.js: ${Object.keys(files).length} files (${kb} KB), game: ${game ? game.scripts.length + ' scripts, online at /' : 'not in repo (test page at /)'}, city layout: ${layout ? 'city-data.js' : 'built-in'}`);
