// Home upgrades (Claude-owned): purchases, rest perks with cooldowns, grow tent, goal bonus, save.
const assert = require('node:assert/strict');
const H = require('../home-data.js');
const T0 = 1_000_000_000;
const s = H.clean({}, T0);
assert.deepEqual(s.owned, []);
assert.deepEqual(H.rest(s, T0), { wellRested: false, rounds: 0, clearHeat: false }, 'no furniture, no perks');
const w = { cash: 3000 };
assert.deepEqual(H.buy(s, w, 'bed'), { ok: true, price: 2500 });
assert.equal(H.buy(s, w, 'bed').reason, 'Already owned');
assert.equal(H.buy(s, w, 'scanner').reason, 'Not enough cash');
assert.equal(H.buy(s, { cash: 1e6 }, 'jacuzzi').reason, 'Unknown item');
assert.deepEqual(H.buy(s, { cash: 2000 }, 'scanner', 0.45), { ok: true, price: 2000 }, 'discount floor 50%');
console.log('PASS: buying furniture with discount and gating');
H.buy(s, { cash: 1e6 }, 'locker');
let r = H.rest(s, T0 + 1e9);
assert.deepEqual(r, { wellRested: true, rounds: 60, clearHeat: true });
r = H.rest(s, T0 + 1e9 + 60000);
assert.deepEqual(r, { wellRested: true, rounds: 0, clearHeat: false }, 'locker and scanner on cooldown');
r = H.rest(s, T0 + 1e9 + H.SCANNER_COOLDOWN);
assert.equal(r.clearHeat, true); assert.equal(r.rounds, 0);
r = H.rest(s, T0 + 1e9 + H.LOCKER.cooldown);
assert.equal(r.rounds, 60);
console.log('PASS: rest perks and their cooldowns');
const t = H.clean({ owned: ['tent'], tent: { stock: 0, since: T0 } }, T0);
assert.equal(H.growTent(t, T0 + H.TENT.every - 1), 0);
assert.equal(H.growTent(t, T0 + H.TENT.every * 2 + 5), 2); assert.equal(t.tent.stock, 2);
assert.equal(H.growTent(t, T0 + H.TENT.every * 100), 4, 'caps at max'); assert.equal(t.tent.stock, H.TENT.max);
const fast = H.clean({ owned: ['tent'], tent: { stock: 0, since: T0 } }, T0);
assert.equal(H.growTent(fast, T0 + H.TENT.every, 0.5), 2, 'farming perk halves grow time');
assert.equal(H.growTent(H.clean({}, T0), T0 + 1e9), 0, 'no tent, no weed');
console.log('PASS: grow tent production, cap and farming speed-up');
assert.equal(H.goalBonus(H.clean({ owned: ['trophies'] })), 1.1); assert.equal(H.goalBonus(s), 1);
const d = H.clean({ owned: ['bed', 'bed', 'x'], tent: { stock: 99, since: T0 + 5 }, lockerAt: -1, scannerAt: T0 * 9 }, T0);
assert.deepEqual(d.owned, ['bed']); assert.equal(d.tent.stock, H.TENT.max); assert.equal(d.tent.since, T0, 'future timestamps reset');
assert.equal(d.lockerAt, 0); assert.equal(d.scannerAt, 0);
for (const it of H.ITEMS) assert.ok(it.x > 40 && it.x < 600 && it.y > 40 && it.y < 400, it.id + ' inside the room');
console.log('PASS: trophy bonus, save cleaning, furniture inside the room');
