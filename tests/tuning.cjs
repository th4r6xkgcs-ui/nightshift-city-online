// Car tuning (Claude-owned): per-car upgrades, prices, paint and save cleaning.
const assert = require('node:assert/strict');
const T = require('../tuning-data.js');
const st = T.clean({});
const car = { id: 'car-0', owned: true, color: '#c84659' }, stolen = { id: 'car-3', owned: false, stolen: true };
for (const u of T.UPGRADES) assert.equal(T.factor(st, 'car-0', u.id), 1, 'stock car is unchanged');
const w = { cash: 10000 };
assert.deepEqual(T.upgrade(st, w, car, 'engine'), { ok: true, price: 800, level: 1 });
assert.ok(Math.abs(T.factor(st, 'car-0', 'engine') - 1.08) < 1e-9);
assert.equal(T.factor(st, 'car-1', 'engine'), 1, 'upgrades are per car');
assert.equal(T.upgrade(st, w, stolen, 'engine').reason, 'You can only tune cars you own');
assert.equal(T.upgrade(st, w, car, 'turbo').reason, 'Unknown upgrade');
T.upgrade(st, w, car, 'engine'); T.upgrade(st, w, car, 'engine');
assert.equal(T.upgrade(st, w, car, 'engine').reason, 'Already maxed');
assert.equal(w.cash, 10000 - 800 - 2000 - 4500);
assert.equal(T.upgrade(st, { cash: 10 }, car, 'armor').reason, 'Not enough cash');
console.log('PASS: per-car upgrades, gating and max level');
assert.equal(T.nextPrice(st, 'car-0', 'armor', 0.7), 490, 'charisma discount applies');
assert.equal(T.nextPrice(st, 'car-0', 'armor', 0.1), 350, 'discount floor is 50%');
for (let i = 0; i < 3; i++) T.upgrade(st, { cash: 1e6 }, car, 'armor');
assert.ok(Math.abs(T.factor(st, 'car-0', 'armor') - 0.55) < 1e-9, 'max armor takes 55% damage');
assert.equal(T.totalLevels(st), 6); assert.equal(T.bestCar(st), 6);
console.log('PASS: prices, discount and armor factor');
const pw = { cash: 1000 };
assert.deepEqual(T.paint(pw, car, '#ff4fd8'), { ok: true, price: 150 }); assert.equal(car.color, '#ff4fd8');
assert.equal(T.paint(pw, car, '#ff4fd8').reason, 'Already that color');
assert.equal(T.paint(pw, car, '#123456').reason, 'Unknown paint');
assert.equal(T.paint(pw, stolen, '#3d99d6').reason, 'You can only paint cars you own');
for (const p of T.PAINTS) assert.match(p.hex, /^#[0-9a-f]{6}$/i, 'paint must pass the game vehicle save color check');
const dirty = T.clean({ cars: { 'car-0': { engine: 9, handling: -1, armor: 'x' }, 'car-x': { engine: 1 }, 'car-2': { engine: 0 } } });
assert.deepEqual(dirty.cars, { 'car-0': { engine: 3, handling: 0, armor: 0 } });
console.log('PASS: paint rules and tuning save cleaning');
